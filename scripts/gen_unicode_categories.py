#!/usr/bin/env python3
"""Generate Erlan Unicode L/M/N and White_Space lookup, no host calls at runtime.

Used by Qwen's published pre-tokenizer regex. Regenerate deliberately when
upgrading Python's Unicode database; the checked-in output pins its version.
"""
from pathlib import Path
import unicodedata

SPACE = {9, 10, 11, 12, 13, 32, 0x85, 0xA0, 0x1680, 0x2028, 0x2029,
         0x202F, 0x205F, 0x3000, *range(0x2000, 0x200B)}

def category(cp):
    return 8 if cp in SPACE else {'L': 1, 'M': 2, 'N': 4}.get(unicodedata.category(chr(cp))[0], 0)

def main():
    ranges = []
    begin = 0
    previous = category(0)
    for cp in range(1, 0x110001):
        current = category(cp) if cp < 0x110000 else -1
        if current != previous:
            if previous: ranges.append((begin, cp - 1, previous))
            begin, previous = cp, current

    def tree(rows, indent='    '):
        if not rows: return indent + 'return 0;\n'
        middle = len(rows) // 2
        lo, hi, value = rows[middle]
        return (f'{indent}if cp < {lo} {{\n' + tree(rows[:middle], indent + '    ') +
                f'{indent}}}\n{indent}if cp <= {hi} {{ return {value}; }}\n' + tree(rows[middle + 1:], indent))
    source = (f'// Generated by scripts/gen_unicode_categories.py; Unicode {unicodedata.unidata_version}.\n'
              '// Class bits: Letter=1, Mark=2, Number=4, White_Space=8.\n'
              '// Balanced comparisons keep tables out of the service stack/BSS.\n'
              'fn unicode_class(cp: u32) -> u64 {\n' + tree(ranges) + '}\n')
    dest = Path(__file__).resolve().parents[1] / 'services/model/unicode.e'
    dest.write_text(source, encoding='utf-8')
    print(f'{len(ranges)} Unicode ranges -> {dest}')

if __name__ == '__main__': main()
