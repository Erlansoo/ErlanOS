#!/usr/bin/env python3
"""Bake licensed DejaVu fonts for the freestanding document preview (Pillow)."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/fonts"
names = ["DejaVuSerif", "DejaVuSans"]
metrics, atlases, manifest = [], [], {}
for name in names:
    path = OUT / (name + ".ttf")
    font = ImageFont.truetype(str(path), 32)
    widths, data = [], []
    for code in range(32, 256):
        ch = chr(code)
        widths.append(round(font.getlength(ch) * 64))
        glyph = Image.new("L", (40, 48))
        ImageDraw.Draw(glyph).text((3, 36), ch, font=font, fill=255, anchor="ls")
        pixels = list(glyph.getdata())
        for i in range(0, len(pixels), 2):
            data.append(((pixels[i] + 8) // 17 << 4) | ((pixels[i + 1] + 8) // 17))
    metrics.append(widths)
    atlases.append(data)
    manifest[name] = {"sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "advances_2048": widths}
header = ["/* Generated by scripts/gen_doc_fonts.py; see assets/fonts/LICENSE. */", "#ifndef ERLAN_DOC_FONT_DATA_H", "#define ERLAN_DOC_FONT_DATA_H", "#include <stdint.h>"]
header.append("static const uint16_t doc_advances[2][224] = {" + ",\n".join("{" + ",".join(map(str, row)) + "}" for row in metrics) + "};")
header.append("#ifndef DOC_FONT_METRICS_ONLY")
header.append("static const uint8_t doc_atlas[2][215040] = {")
for atlas in atlases:
    header.append("{")
    for start in range(0, len(atlas), 64):
        header.append(",".join(str(v) for v in atlas[start:start+64]) + ",")
    header.append("},")
header.extend(["};", "#endif", "#endif", ""])
(OUT / "font_data.h").write_text("\n".join(header), encoding="ascii")
(OUT / "metrics.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
print("DejaVu Serif/Sans: metrics and 4-bit Latin-1 atlases generated")
